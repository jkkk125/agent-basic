import 'dotenv/config'
import { OpenAI } from 'openai'
import { toResponseInputItems } from 'openai/lib/responses/ResponseInputItems'

const openai = new OpenAI({
  apiKey: process.env.API_KEY,
  baseURL: process.env.BASE_URL,
});

const tools: OpenAI.Responses.Tool[] = [
  {
    type: 'function',
    name: 'get_horoscope',
    description: "Get today's horoscope for an astrological sign",
    parameters: {
      type: 'object',
      properties: {
        sign: {
          type: 'string',
          description: 'The astrological sign to get the horoscope for',
        }
      },
      required: ['sign'],
      additionalProperties: false,
    },
    strict: true,
    allowed_callers: [
      'direct' // 默认值 允许模型直接发起 tool call
      
    ]
  }
]

function getHoroscope(sign: string) {
  return `Today's horoscope for ${sign} is: Next Tuesday you will befriend a baby otter.`;
}

const input: OpenAI.Responses.ResponseInput = [
  {
    role: 'user',
    content: 'What is the horoscope for today? I am an Aquarius.'
  }
]

let response = await openai.responses.create({
  model: process.env.MODEL_NAME as string,
  input,
  tools,
})

input.push(...toResponseInputItems(response.output))

for (const item of response.output) {
  if (item.type !== 'function_call') {
    continue
  }

  if (item.name === 'get_horoscope') {
    const args = JSON.parse(item.arguments)
    const result = getHoroscope(args.sign)
    input.push({
      type: 'function_call_output',
      call_id: item.call_id,
      output: result
    })
  }
}

response = await openai.responses.create({
  model: process.env.MODEL_NAME as string,
  input,
  tools,
  instructions: 'Respond only with a horoscope generated by a tool.'
})

console.log(response.output_text)